'use strict';
const assert=require('node:assert/strict');
const {create,warmSource}=require('../viewer/section-load-scheduler.js');
const deferred=()=>{let resolve;const promise=new Promise(r=>resolve=r);return {promise,resolve};};
const flush=async()=>{for(let i=0;i<15;i++)await Promise.resolve();};
async function main(){
  const scheduler=create(), gates=[deferred(),deferred(),deferred()], starts=[];
  const one=scheduler.enqueue({key:'he-one',kind:'image',priority:10,run:()=>{starts.push('he-one');return gates[0].promise;}});
  const two=scheduler.enqueue({key:'he-two',kind:'image',priority:10,run:()=>{starts.push('he-two');return gates[1].promise;}});
  const msi=scheduler.enqueue({key:'msi',kind:'msi',priority:10,run:()=>{starts.push('msi');return gates[2].promise;}});
  await flush();assert.deepEqual(starts,['he-one','msi'],'a blocked HE must not hold the independent MSI lane');
  assert.deepEqual(scheduler.snapshot(),{active:2,images:1,queued:1});
  let background=false;
  const bg=scheduler.enqueue({key:'tic',priority:40,run:()=>{background=true;return true;}});
  gates[2].resolve(true);await msi;await flush();assert.equal(background,false,'background waits for all foreground including queued HE');
  gates[0].resolve(true);await one;await flush();assert.deepEqual(starts,['he-one','msi','he-two']);
  gates[1].resolve(true);await two;await bg;assert.equal(background,true);
  const dedup=create({concurrency:1}), gate=deferred();let reads=0;
  const a=dedup.enqueue({key:'same',priority:20,run:()=>{reads++;return gate.promise;}});
  const b=dedup.enqueue({key:'same',priority:0,run:()=>{throw Error('duplicate');}});
  assert.equal(a,b);await flush();assert.equal(reads,1);gate.resolve('pixels');assert.equal(await b,'pixels');
  let wanted=true;const cancel=create({concurrency:1}), busy=deferred();
  const running=cancel.enqueue({key:'busy',run:()=>busy.promise});
  const hidden=cancel.enqueue({key:'hidden',valid:()=>wanted,run:()=>{throw Error('hidden section started');}});
  wanted=false;cancel.refresh();assert.equal(await hidden,false);
  const stale=cancel.enqueue({key:'other-project',run:()=>{throw Error('old project started');}});
  cancel.dispose();assert.equal(await stale,false);busy.resolve(true);assert.equal(await running,false);
  const required=create({concurrency:1}),hold=deferred();let visible=true,alive=true;
  const blocker=required.enqueue({key:'held',run:()=>hold.promise});
  const exportJob=required.enqueue({key:'required',automatic:true,valid:()=>visible&&alive,baseValid:()=>alive,run:()=>42});
  required.promote('required');visible=false;
  required.cancelWhere(job=>job.automatic&&!job.started);
  hold.resolve();await blocker;assert.equal(await exportJob,42,'explicit export survives later deselection');
  const ended=create({concurrency:1}),wait=deferred();
  const pending=ended.enqueue({key:'held',run:()=>wait.promise});
  const switched=ended.enqueue({key:'old-project',automatic:true,valid:()=>alive,baseValid:()=>alive,run:()=>{throw Error('stale project');}});
  ended.promote('old-project');alive=false;wait.resolve();await pending;assert.equal(await switched,false,'promotion still checks project lifetime');
  const abortable=create({concurrency:2}), download=deferred();let downloadSignal;
  const automatic=abortable.enqueue({key:'download',automatic:true,run:({signal})=>{downloadSignal=signal;return download.promise;}});
  await flush();abortable.cancelWhere(job=>job.automatic);
  assert.equal(downloadSignal.aborted,true,'started source work receives cancellation');
  assert.equal(automatic.signal,downloadSignal);assert.equal(await automatic,false);
  const replacement=abortable.enqueue({key:'download',automatic:true,run:({signal})=>{assert.equal(signal.aborted,false);return 'new';}});
  assert.notEqual(automatic,replacement);assert.equal(await replacement,'new','cancelled work is not rejoined');
  download.resolve('stale');await flush();
  const preserved=create(), needed=deferred();let neededSignal;
  const foreground=preserved.enqueue({key:'export-source',automatic:true,run:({signal})=>{neededSignal=signal;return needed.promise;}});
  await flush();const explicit=preserved.enqueue({key:'export-source',automatic:false,run:()=>{throw Error('duplicate source');}});
  preserved.cancelWhere(job=>job.automatic);assert.equal(neededSignal.aborted,false);
  needed.resolve(true);assert.equal(await explicit,true);assert.equal(explicit,foreground);
  let active=0,max=0;const cold=deferred();
  const sourceA=warmSource(async()=>{max=Math.max(max,++active);await cold.promise;active--;});
  const sourceB=warmSource(async()=>{max=Math.max(max,++active);active--;});
  await flush();assert.equal(active,1);cold.resolve();await Promise.all([sourceA,sourceB]);assert.equal(max,1,'different cold sources never initialize concurrently');
  console.log('Section load scheduler regression: PASS');
}
main().catch(e=>{console.error(e);process.exitCode=1;});
